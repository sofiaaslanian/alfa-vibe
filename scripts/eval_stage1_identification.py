EXPECTED_TYPES = [
    "PERSON", "PLACE_OF_BIRTH", "CITIZENSHIP", "PASSPORT_ISSUER",
    "ADDRESS", "CARDHOLDER_NAME", "BIRTH_DATE", "PASSPORT",
    "SUBDIVISION_CODE", "PASSPORT_ISSUE_DATE", "DRIVER_LICENSE",
    "CVV", "PIN", "EMAIL", "PHONE", "INN", "PAYMENT_CARD",
]

assert list(CASES) == EXPECTED_TYPES
assert all(len(v["positive"]) == 5 and len(v["negative"]) == 5 for v in CASES.values())
assert sum(len(v["positive"]) + len(v["negative"]) for v in CASES.values()) == 170


def mask_types(findings):
    return {
        f.type
        for f in findings
        if getattr(f, "decision", "mask") == "mask"
    }


def main():
    cfg = load_config("config.yaml")
    assert cfg.systems["autotest"].use_context_ml is True

    svc = ProcessService(cfg, MemoryStateStore())
    details = []
    summary = {}
    total_ok = 0

    for target, group in CASES.items():
        pos_ok = 0
        neg_ok = 0

        for kind in ("positive", "negative"):
            for idx, text in enumerate(group[kind], 1):
                findings = svc.detect(text, "autotest")
                found = target in mask_types(findings)
                expected = kind == "positive"
                ok = found == expected
                total_ok += int(ok)
                if kind == "positive":
                    pos_ok += int(ok)
                else:
                    neg_ok += int(ok)
                details.append({
                    "type": target,
                    "kind": kind,
                    "n": idx,
                    "text": text,
                    "expected_target": expected,
                    "target_found": found,
                    "ok": ok,
                    "all_mask_types": sorted(mask_types(findings)),
                    "findings": [f.to_dict() for f in findings],
                })

        summary[target] = {
            "positive": f"{pos_ok}/5",
            "negative": f"{neg_ok}/5",
            "total": f"{pos_ok + neg_ok}/10",
        }

    result = {
        "profile": "autotest",
        "context_ml": True,
        "cases": 170,
        "passed": total_ok,
        "accuracy": round(total_ok / 170, 4),
        "summary": summary,
        "failures": [x for x in details if not x["ok"]],
        "details": details,
    }

    Path("stage1_identification_results.json").write_text(
        json.dumps(result, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )

    print("STAGE1_TOTAL", f"{total_ok}/170", f"{100*total_ok/170:.1f}%")
    for typ in EXPECTED_TYPES:
        s = summary[typ]
        print(f"{typ:22} pos={s['positive']} neg={s['negative']} total={s['total']}")
    print("FAILURES", 170-total_ok)
    for f in result["failures"]:
        print(
            "FAIL",
            f["type"],
            f["kind"],
            f["n"],
            "|",
            f["text"],
            "| found:",
            ",".join(f["all_mask_types"]) or "-",
        )


if __name__ == "__main__":
    main()
