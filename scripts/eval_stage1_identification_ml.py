def mask_types(svc: ProcessService, text: str) -> list[str]:
    return sorted({f.type for f in svc.detect(text, "autotest") if getattr(f, "decision", "mask") == "mask"})

def main() -> None:
    cfg = load_config("config.yaml")
    assert cfg.systems["autotest"].use_context_ml is True, "autotest ML must be enabled"
    svc = ProcessService(cfg, MemoryStateStore())
    rows = []
    by_type = defaultdict(lambda: {"positive_passed":0,"positive_total":0,"negative_passed":0,"negative_total":0})
    for typ, groups in CASES.items():
        for polarity, texts in groups.items():
            for idx, text in enumerate(texts, 1):
                found = mask_types(svc, text)
                detected = typ in found
                expected = polarity == "positive"
                passed = detected == expected
                key = "positive" if expected else "negative"
                by_type[typ][f"{key}_total"] += 1
                by_type[typ][f"{key}_passed"] += int(passed)
                rows.append({
                    "type": typ,
                    "polarity": key,
                    "case": idx,
                    "text": text,
                    "expected_target_detected": expected,
                    "actual_target_detected": detected,
                    "all_mask_types": found,
                    "passed": passed,
                })
    pos = [r for r in rows if r["polarity"] == "positive"]
    neg = [r for r in rows if r["polarity"] == "negative"]
    report = {
        "profile": "autotest",
        "context_ml_enabled": True,
        "method": "target-type presence among final mask findings",
        "total": len(rows),
        "passed": sum(r["passed"] for r in rows),
        "positive_total": len(pos),
        "positive_passed": sum(r["passed"] for r in pos),
        "negative_total": len(neg),
        "negative_passed": sum(r["passed"] for r in neg),
        "by_type": dict(by_type),
        "failed": [r for r in rows if not r["passed"]],
    }
    Path("stage1-identification-results.json").write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({k:v for k,v in report.items() if k not in {"failed","by_type"}}, ensure_ascii=False, indent=2))
    print("BY_TYPE")
    for typ, stats in report["by_type"].items():
        print(typ, stats)
    print("FAILED")
    for row in report["failed"]:
        print(json.dumps(row, ensure_ascii=False))
    if len(rows) != 170:
        raise SystemExit(f"Expected 170 cases, got {len(rows)}")

if __name__ == "__main__":
    main()
